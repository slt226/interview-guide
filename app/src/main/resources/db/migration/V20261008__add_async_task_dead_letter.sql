-- 异步任务死信表
--  Redis Stream 消费失败且超过重试上限后，统一归档到此表，支持在管理页手动重投（replay）。
--  与 AbstractStreamConsumer 的 MAX_RETRY_COUNT=3 衔接：3 次失败后 markFailed 写入本表。
CREATE TABLE async_task_dead_letter (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stream_key VARCHAR(100) NOT NULL,
  group_name VARCHAR(100) NOT NULL,
  message_id VARCHAR(64),
  task_type VARCHAR(50),
  payload TEXT NOT NULL,
  payload_identifier VARCHAR(200),
  error_message TEXT,
  status VARCHAR(20) NOT NULL,
  retry_count INTEGER DEFAULT 0,
  replay_count INTEGER DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL DEFAULT now(),
  last_replay_at TIMESTAMP(6),
  updated_at TIMESTAMP(6),
  CONSTRAINT async_task_dead_letter_status_check
    CHECK (status IN ('DEAD', 'REPLAYED', 'RESOLVED'))
);

-- 按消费来源（stream）查询待重投记录
CREATE INDEX idx_dead_letter_stream_key ON async_task_dead_letter (stream_key);
-- 按状态筛选（DEAD / REPLAYED / RESOLVED）
CREATE INDEX idx_dead_letter_status ON async_task_dead_letter (status);
-- 按业务标识定位（如 knowledge_base_id / session_id），用于幂等去重与排查
CREATE INDEX idx_dead_letter_payload_identifier ON async_task_dead_letter (payload_identifier);

COMMENT ON COLUMN async_task_dead_letter.status IS 'DEAD=已归档待重投, REPLAYED=已重投, RESOLVED=已人工解决';
COMMENT ON COLUMN async_task_dead_letter.payload_identifier IS '业务唯一标识，用于重投时幂等去重（如 knowledge_base_id / session_id）';
